import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const scoreDir = resolve(root, "docs/assets/scores");
const catalog = JSON.parse(await readFile(resolve(scoreDir, "catalog.json"), "utf8"));
const serialize = value => JSON.stringify(value).replaceAll("<", "\\u003c");
const embeddedCatalog = [];

for (const score of catalog) {
  const manifest = JSON.parse(await readFile(resolve(scoreDir, `${score.id}.json`), "utf8"));
  const musicXmlText = (await readFile(resolve(scoreDir, manifest.musicXml), "utf8")).replaceAll("\r\n", "\n");
  const payload = serialize({ ...manifest, musicXmlText });
  const hash = createHash("sha256").update(payload).digest("hex").slice(0, 12);
  const asset = `${score.id}.bundle.js`;
  await writeFile(resolve(scoreDir, asset),
    `// Generated by scripts/build-score-bundles.mjs; edit the MusicXML/JSON sources.\n` +
    `(window.__tunerBuiltInScores ||= Object.create(null))[${serialize(score.id)}] = ${payload};\n`);
  embeddedCatalog.push({ ...score, assetScript: `assets/scores/${asset}?v=${hash}` });
}

const htmlPath = resolve(root, "docs/index.html");
const html = await readFile(htmlPath, "utf8");
const marker = /<script id="score-catalog" type="application\/json">[\s\S]*?<\/script>/;
if (!marker.test(html)) throw new Error("Missing embedded score catalog in docs/index.html");
await writeFile(htmlPath, html.replace(marker, () =>
  `<script id="score-catalog" type="application/json">${serialize(embeddedCatalog)}</script>`));
console.log(`Built ${catalog.length} lazy-loaded scores and the embedded catalog.`);
